import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://127.0.0.1:3105/");
await p.fill("#box", "We run girls' coding clubs."); await p.press("#box", "Enter");
await p.locator(".msg.bot").nth(1).locator(".tools").waitFor();
await p.getByRole("button", { name: /Framework views/ }).click();
const d = p.getByRole("dialog", { name: "Framework views" });
await d.getByRole("tab", { name: "Logic model" }).click(); await p.waitForTimeout(300);
await d.locator(".slide").screenshot({ path: "shots/fw-logic.png" });
await b.close();
